package main

import (
	"context"
	"errors"
	"fmt"
	"io"
	"strings"

	cli "github.com/urfave/cli/v3"

	"github.com/beat/backend/internal/agentinstall"
)

const (
	maxJoinTokenInput = 1024
	maximumSSHPort    = 65535
)

type agentActions struct {
	enableUpdates func(context.Context, agentinstall.UpdateOptions) error
	helper        func(context.Context, string) error
	run           func(context.Context, string) error
	join          func(context.Context, agentinstall.JoinOptions) (agentinstall.Summary, error)
	install       func(context.Context, string) error
	uninstall     func(context.Context, agentinstall.UninstallOptions) (agentinstall.UninstallSummary, error)
	enroll        func(context.Context, agentinstall.GrantOptions) (agentinstall.Summary, error)
}

func agentJoinCommand(action agentActions) *cli.Command {
	return &cli.Command{
		Name: "join", Usage: "register this Linux node and start its systemd service (requires root)",
		Flags: []cli.Flag{
			&cli.StringFlag{Name: "server", Usage: "Beat server origin, for example https://beat.example.com", Required: true},
			&cli.StringFlag{Name: "token", Usage: "one-time token generated by the Beat server"},
			&cli.BoolFlag{Name: "token-stdin", Usage: "read the join token from standard input"},
			&cli.BoolFlag{Name: "allow-http", Usage: "explicitly allow sending credentials over unencrypted HTTP"},
			&cli.StringFlag{Name: "name", Usage: "node name (defaults to this machine's hostname)"},
			&cli.StringFlag{Name: "host", Usage: "reachable node address (defaults to the server-observed source IP)"},
			&cli.IntFlag{Name: "ssh-port", Usage: "SSH port (defaults to sshd configuration, then 22)"},
		},
		Action: func(ctx context.Context, command *cli.Command) error {
			return runJoinCommand(ctx, command, action)
		},
	}
}

func runJoinCommand(ctx context.Context, command *cli.Command, action agentActions) error {
	if command.Args().Len() != 0 {
		return errors.New("join does not accept positional arguments")
	}
	if command.IsSet("config") {
		return errors.New("join generates /etc/beat-agent/agent.json; --config is for foreground mode or service install")
	}
	if command.IsSet("ssh-port") && (command.Int("ssh-port") < 1 || command.Int("ssh-port") > maximumSSHPort) {
		return errors.New("ssh-port must be between 1 and 65535")
	}
	token, err := readJoinToken(command)
	if err != nil {
		return err
	}
	result, err := action.join(ctx, agentinstall.JoinOptions{
		ServerURL: command.String("server"), Token: token, AllowHTTP: command.Bool("allow-http"),
		Name: command.String("name"), Host: command.String("host"), SSHPort: command.Int("ssh-port"),
	})
	if err != nil {
		return err
	}
	_, err = fmt.Fprintf(command.Root().Writer,
		"Node registered: %s\n%s is enabled and active.\nServer: %s\nConfig: %s\n",
		result.NodeID, agentinstall.ServiceName, result.ServerURL, result.ConfigPath)
	return err
}

func readJoinToken(command *cli.Command) (string, error) {
	token := command.String("token")
	if command.Bool("token-stdin") {
		if token != "" {
			return "", errors.New("use either --token or --token-stdin")
		}
		data, err := io.ReadAll(io.LimitReader(command.Root().Reader, maxJoinTokenInput+1))
		if err != nil {
			return "", fmt.Errorf("read join token: %w", err)
		}
		if len(data) > maxJoinTokenInput {
			return "", errors.New("join token input is too long")
		}
		token = strings.TrimSpace(string(data))
	}
	if token == "" {
		return "", errors.New("--token or --token-stdin is required")
	}
	return token, nil
}

func agentServiceCommand(action agentActions) *cli.Command {
	return &cli.Command{
		Name: "service", Usage: "manage the agent systemd service",
		Commands: []*cli.Command{agentEnableUpdatesCommand(action), agentServiceInstallCommand(action), agentServiceUninstallCommand(action)},
	}
}

func agentServiceInstallCommand(action agentActions) *cli.Command {
	return &cli.Command{
		Name: "install", Usage: "install systemd using an agent config or restore the default config from its saved receipt (requires root)",
		Flags: []cli.Flag{&cli.StringFlag{Name: "config", Value: agentinstall.DefaultConfigPath,
			Usage: "path to the existing agent JSON config"}},
		Action: func(ctx context.Context, command *cli.Command) error {
			if command.Args().Len() != 0 {
				return errors.New("service install does not accept positional arguments")
			}
			if err := action.install(ctx, command.String("config")); err != nil {
				return err
			}
			_, err := fmt.Fprintf(command.Root().Writer, "%s is enabled and active.\n", agentinstall.ServiceName)
			return err
		},
	}
}

func agentServiceUninstallCommand(action agentActions) *cli.Command {
	return &cli.Command{
		Name: "uninstall", Usage: "stop and remove the agent systemd service (requires root)",
		Flags: []cli.Flag{&cli.BoolFlag{Name: "purge",
			Usage: "also delete the agent config, identity and enrollment state under /etc/beat-agent"}},
		Action: func(ctx context.Context, command *cli.Command) error {
			if command.Args().Len() != 0 {
				return errors.New("service uninstall does not accept positional arguments")
			}
			summary, err := action.uninstall(ctx, agentinstall.UninstallOptions{Purge: command.Bool("purge")})
			if err != nil {
				return err
			}
			return writeUninstallSummary(command.Root().Writer, summary)
		},
	}
}

func writeUninstallSummary(writer io.Writer, summary agentinstall.UninstallSummary) error {
	for _, path := range summary.Removed {
		if _, err := fmt.Fprintf(writer, "Removed %s\n", path); err != nil {
			return err
		}
	}
	for _, path := range summary.Retained {
		if _, err := fmt.Fprintf(writer,
			"Retained %s\nRe-run with --purge to delete the agent config and identity.\n", path); err != nil {
			return err
		}
	}
	return nil
}
