import { act, renderHook } from "@testing-library/react"
import { afterEach, beforeEach, expect, it, vi } from "vitest"
import { useOperationResource } from "./use-operation-resource"
beforeEach(()=>vi.useFakeTimers())
afterEach(()=>{vi.useRealTimers();vi.restoreAllMocks()})
it("ignores late results from a superseded resource",async()=>{
 let resolve!: (value:string)=>void
 const first=vi.fn((_signal:AbortSignal)=>new Promise<string>(done=>{resolve=done}))
 const second=vi.fn(async(_signal:AbortSignal)=>"current")
 const hook=renderHook(({load})=>useOperationResource(load),{initialProps:{load:first as (signal:AbortSignal)=>Promise<string>}})
 hook.rerender({load:second})
 await act(async()=>{await vi.advanceTimersByTimeAsync(0)})
 expect(hook.result.current.data).toBe("current")
 expect(first.mock.calls[0][0].aborted).toBe(true)
 await act(async()=>{resolve("obsolete");await vi.advanceTimersByTimeAsync(0)})
 expect(hook.result.current.data).toBe("current")
 hook.unmount()
})
it("retains last good data with refresh errors and pauses when hidden",async()=>{
 const hidden=vi.spyOn(document,"hidden","get").mockReturnValue(false)
 const load=vi.fn(async(_signal:AbortSignal)=>"first")
 const hook=renderHook(()=>useOperationResource(load,1000))
 await act(async()=>{await vi.advanceTimersByTimeAsync(0)})
 load.mockRejectedValueOnce(new Error("refresh unavailable"))
 await act(async()=>{await vi.advanceTimersByTimeAsync(1000)})
 expect(hook.result.current).toMatchObject({data:"first",error:"refresh unavailable",loading:false})
 act(()=>{hidden.mockReturnValue(true);document.dispatchEvent(new Event("visibilitychange"))})
 await act(async()=>{await vi.advanceTimersByTimeAsync(5000)})
 expect(load).toHaveBeenCalledTimes(2)
 await act(async()=>{hidden.mockReturnValue(false);document.dispatchEvent(new Event("visibilitychange"));await vi.advanceTimersByTimeAsync(0)})
 expect(load).toHaveBeenCalledTimes(3)
 act(()=>hook.result.current.reload())
 await act(async()=>{await vi.advanceTimersByTimeAsync(0)})
 expect(load).toHaveBeenCalledTimes(4)
 hook.unmount()
 await act(async()=>{await vi.advanceTimersByTimeAsync(5000)})
 expect(load).toHaveBeenCalledTimes(4)
})
it("waits for visibility when initially hidden even without refresh",async()=>{
 const hidden=vi.spyOn(document,"hidden","get").mockReturnValue(true)
 const load=vi.fn(async()=>"ready")
 const hook=renderHook(()=>useOperationResource(load))
 expect(load).not.toHaveBeenCalled()
 await act(async()=>{hidden.mockReturnValue(false);document.dispatchEvent(new Event("visibilitychange"));await vi.advanceTimersByTimeAsync(0)})
 expect(hook.result.current.data).toBe("ready")
 hook.unmount()
})
